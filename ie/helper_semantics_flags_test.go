func TestHelperSemanticFlags(t *testing.T) {
	for _, tc := range helperSemanticFlags() {
		t.Run(fmt.Sprintf("%s/%s", tc.typ, tc.name), func(t *testing.T) {
			call := func(i *ie.IE) bool { return reflect.ValueOf(i).MethodByName(tc.name).Call(nil)[0].Bool() }
			for label, input := range map[string]*ie.IE{"nil": nil, "wrong-type": ie.New(0xffff, make([]byte, 64)), "null": ie.New(tc.typ, nil)} {
				t.Run(label, func(t *testing.T) {
					if call(input) {
						t.Fatal("reported flag on absent or wrong value")
					}
				})
			}
			for bit := 0; bit < 8; bit++ {
				t.Run(fmt.Sprintf("bit-%d", bit+1), func(t *testing.T) {
					payload := make([]byte, 64)
					payload[tc.octet] = 1 << bit
					// PQPM selects a nonempty count-delimited QFI list (clause 8.2.156).
					if tc.typ == ie.PMFControlInformation && payload[0]&4 != 0 {
						payload[1] = 1
						payload[2] = 9
					}
					if got, want := call(ie.New(tc.typ, payload)), tc.mask&(1<<bit) != 0; got != want {
						t.Fatalf("flag=%v; want %v (%s)", got, want, tc.clause)
					}
				})
			}
			if tc.octet > 0 {
				t.Run("truncated", func(t *testing.T) {
					if call(ie.New(tc.typ, make([]byte, tc.octet))) {
						t.Fatal("reported missing flag octet")
					}
				})
			}
		})
	}
}
