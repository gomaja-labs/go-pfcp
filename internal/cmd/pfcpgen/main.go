func run() error {
	target := flag.String("target", "", "ie or message")
	root := flag.String("root", "..", "repository root")
	flag.Parse()
	if *target != "ie" && *target != "message" {
		return fmt.Errorf("-target must be ie or message")
	}
	c, err := spec.Load()
	if err != nil {
		return err
	}
	files, err := generate(c)
	if err != nil {
		return err
	}
	names := make([]string, 0, len(files))
	for n := range files {
		if strings.HasPrefix(n, *target+"/") {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	for _, n := range names {
		if err := os.WriteFile(filepath.Join(*root, filepath.FromSlash(n)), files[n], 0o644); err != nil {
			return err
		}
	}
	return nil
}
func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
